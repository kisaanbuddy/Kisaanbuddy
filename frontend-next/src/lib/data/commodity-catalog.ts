/**
 * Normalizes user search input and matches against catalog commodities (English & Hindi)
 */
export function matchCatalogCommodity(query: string): CommodityCatalogItem | null {
  if (!query || !query.trim()) return null
  const q = query.trim().toLowerCase()

  for (const item of COMMODITY_CATALOG) {
    if (
      item.name.toLowerCase() === q ||
      item.hindiName === query.trim() ||
      item.searchKeywords.some((k) => k.toLowerCase() === q || q.includes(k.toLowerCase()))
    ) {
      return item
    }
  }
  return null
}
