/**
 * Normalizes commodity queries to match English keywords (e.g. "Wheat (गेहूं)" -> "wheat").
 */
export function normalizeCommodityQuery(input: string): string {
  if (!input) return ""
  const withoutParens = input.replace(/\s*\([^)]*\)/g, "").trim().toLowerCase()
  // Map common terms
  if (withoutParens.includes("wheat") || withoutParens.includes("gehun") || withoutParens.includes("gehu")) return "wheat"
  if (withoutParens.includes("rice") || withoutParens.includes("chawal") || withoutParens.includes("paddy") || withoutParens.includes("dhan")) return "rice"
  if (withoutParens.includes("soybean") || withoutParens.includes("soyabean")) return "soybean"
  if (withoutParens.includes("cotton") || withoutParens.includes("kapas")) return "cotton"
  if (withoutParens.includes("mustard") || withoutParens.includes("sarson")) return "mustard"
  if (withoutParens.includes("chana") || withoutParens.includes("gram")) return "chana"
  if (withoutParens.includes("tur") || withoutParens.includes("arhar")) return "tur"
  if (withoutParens.includes("onion") || withoutParens.includes("pyaz")) return "onion"
  if (withoutParens.includes("potato") || withoutParens.includes("aaloo") || withoutParens.includes("aalu")) return "potato"
  if (withoutParens.includes("tomato") || withoutParens.includes("tamatar")) return "tomato"
  if (withoutParens.includes("maize") || withoutParens.includes("makka")) return "maize"
  if (withoutParens.includes("groundnut") || withoutParens.includes("mungfali")) return "groundnut"
  return withoutParens
}

export interface HistoricalQueryParams {
  commodity: string
  variety?: string
  market?: string
  state?: string
  district?: string
  days?: number | string
  from_date?: string
  to_date?: string
}

/**
 * Retrieves authentic historical APMC mandi observations based on query criteria.
 * Returns authentic observations and summary statistics only.
 * If data is unavailable, returns available=false and empty observations.
 */
export function queryAuthenticHistoricalPrices(params: HistoricalQueryParams): HistoricalPriceResponse {
  const normCommodity = normalizeCommodityQuery(params.commodity || "")
  const normMarket = (params.market || "").toLowerCase().replace(/\s*(mandi|apmc)\s*/gi, "").trim()
  const normState = (params.state || "").toLowerCase().trim()

  // Calculate cutoff date based on days or from_date
  let cutoffDate: Date | null = null
  const daysNum = Number(params.days) || 0

  // Reference today date based on latest observation in dataset (2026-10-19)
  const referenceDate = new Date("2026-10-19T23:59:59Z")

  if (params.from_date) {
    cutoffDate = new Date(`${params.from_date}T00:00:00Z`)
  } else if (daysNum > 0) {
    cutoffDate = new Date(referenceDate.getTime() - daysNum * 24 * 60 * 60 * 1000)
  }

  const toDateCutoff = params.to_date ? new Date(`${params.to_date}T23:59:59Z`) : null

  // Filter authentic records
  const matchingRecords = AUTHENTIC_AGMARKNET_HISTORICAL_DATA.filter((rec) => {
    // 1. Commodity match
    if (rec.commodity !== normCommodity && !normCommodity.includes(rec.commodity)) {
      return false
    }

    // 2. Market filter if provided (soft match if multiple mandis exist)
    if (normMarket) {
      const recMkt = rec.market_center.toLowerCase()
      if (!recMkt.includes(normMarket) && !normMarket.includes(recMkt.replace(/\s*(mandi|apmc)\s*/gi, ""))) {
        // If state also matched, allow fallback to main state mandi
        if (!normState || !rec.state.toLowerCase().includes(normState)) {
          return false
        }
      }
    }

    // 3. State filter if provided
    if (normState && !rec.state.toLowerCase().includes(normState)) {
      // allow if market center matched specifically
      if (!normMarket || !rec.market_center.toLowerCase().includes(normMarket)) {
        return false
      }
    }

    // 4. Date range filter
    const recDate = new Date(`${rec.arrival_date}T00:00:00Z`)
    if (cutoffDate && recDate < cutoffDate) {
      return false
    }
    if (toDateCutoff && recDate > toDateCutoff) {
      return false
    }

    return true
  })

  // Sort chronologically ascending
  matchingRecords.sort((a, b) => a.arrival_date.localeCompare(b.arrival_date))

  // If no authentic data found
  if (matchingRecords.length === 0) {
    return {
      commodity: params.commodity,
      variety: params.variety,
      market: params.market || "APMC Market",
      state: params.state,
      district: params.district,
      source: "AGMARKNET / Directorate of Marketing & Inspection (data.gov.in)",
      source_url: "https://agmarknet.gov.in",
      available: false,
      records_count: 0,
      observations: [],
      summary: null,
      message: `Historical price records are currently unavailable for ${params.commodity} in official AGMARKNET government archives for the requested date period.`,
      disclaimer: "Official AGMARKNET reference market benchmarks. Historical APMC observations only, not a guaranteed transaction offer.",
      updated_at: new Date().toISOString(),
    }
  }

  // Map to lightweight observations
  const observations: HistoricalObservation[] = matchingRecords.map((r) => ({
    date: r.arrival_date,
    min_price: r.min_price,
    max_price: r.max_price,
    modal_price: r.modal_price,
    arrival_tonnes: r.arrival_quantity,
  }))

  const modals = observations.map((o) => o.modal_price)
  const highest_modal = Math.max(...modals)
  const lowest_modal = Math.min(...modals)
  const average_modal = Math.round(modals.reduce((sum, v) => sum + v, 0) / modals.length)
  const latest_modal = observations[observations.length - 1].modal_price
  const first_modal = observations[0].modal_price

  let change_percent: number | null = null
  let change_direction: "up" | "down" | "neutral" = "neutral"

  // Only calculate trend percentage when multiple genuine observations exist
  if (observations.length >= 2 && first_modal > 0) {
    const diff = latest_modal - first_modal
    change_percent = Number(((diff / first_modal) * 100).toFixed(1))
    if (change_percent > 0.1) change_direction = "up"
    else if (change_percent < -0.1) change_direction = "down"
    else change_direction = "neutral"
  }

  const primaryRec = matchingRecords[matchingRecords.length - 1]

  return {
    commodity: params.commodity,
    variety: primaryRec.variety || params.variety || "FAQ",
    market: primaryRec.market_center || params.market || "APMC Mandi",
    state: primaryRec.state || params.state,
    district: primaryRec.district || params.district,
    source: primaryRec.source_name || "AGMARKNET / Directorate of Marketing & Inspection (data.gov.in)",
    source_url: primaryRec.source_url || "https://agmarknet.gov.in",
    available: true,
    records_count: observations.length,
    observations,
    summary: {
      highest_modal,
      lowest_modal,
      average_modal,
      latest_modal,
      first_modal,
      change_percent,
      change_direction,
      from_date: observations[0].date,
      to_date: observations[observations.length - 1].date,
      data_points: observations.length,
    },
    disclaimer: "Official AGMARKNET reference market benchmarks. Historical APMC observations only, not a guaranteed transaction offer.",
    updated_at: new Date().toISOString(),
  }
}
